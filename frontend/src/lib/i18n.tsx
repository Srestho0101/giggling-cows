export function useI18n() {
  const [lang, setLang] = usePreference<AppLanguage>("cf-language", "en");

  const tr = useCallback(
    (en: string, bn?: string): string => {
      if (lang !== "bn") return en;
      if (bn) return bn;
      return BN_DICTIONARY[en] ?? en;
    },
    [lang]
  );

  const money = useCallback(
    (value: unknown) => formatMoney(value, lang),
    [lang]
  );

  const num = useCallback(
    (value: unknown, digits = 2) => formatNumber(value, digits, lang),
    [lang]
  );

  const integer = useCallback(
    (value: unknown) => formatInteger(value, lang),
    [lang]
  );

  const date = useCallback(
    (iso: string | null | undefined) => formatDateDisplay(iso, lang),
    [lang]
  );

  const enumLabel = useCallback(
    (value: unknown) => formatEnumLabel(value, lang),
    [lang]
  );

  const daysOnFarm = useCallback(
    (value: unknown) => formatDaysOnFarm(value, lang),
    [lang]
  );

  const digits = useCallback(
    (text: string) => toDisplayDigits(text, lang),
    [lang]
  );

  return {
    lang,
    setLang,
    locale: lang === "bn" ? "bn-BD" : "en-GB",
    tr,
    money,
    num,
    integer,
    date,
    enumLabel,
    daysOnFarm,
    digits,
  };
}
